//! `pack.lock`: fully resolved, reproducible content list.

use std::collections::{BTreeSet, HashMap};
use std::path::Path;

use serde::{Deserialize, Serialize};

use super::schema::{ModKind, Source};
use crate::error::{IoContext, Result};
use crate::meta::loader::LoaderKind;
use crate::util;

pub const LOCK_FILE: &str = "pack.lock";

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct LockFile {
    pub lock_version: u32,
    /// Fingerprint of the resolution inputs (mc, loader, all mod specs) at lock time.
    pub inputs: String,
    pub minecraft: String,
    pub loader: LoaderKind,
    /// Concrete loader version ("" for vanilla).
    pub loader_version: String,
    #[serde(default, rename = "entry")]
    pub entries: Vec<LockEntry>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default, PartialEq)]
pub struct LockEntry {
    /// `source:project_id` (url/file: `url:<filename>` / `file:<path>`).
    pub key: String,
    pub source: Source,
    pub kind: ModKind,
    pub project_id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub slug: Option<String>,
    pub name: String,
    #[serde(default)]
    pub version_id: String,
    #[serde(default)]
    pub version_number: String,
    pub filename: String,
    /// Download URL; `None` when manual download is required (CurseForge opt-out) or local file.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sha1: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sha512: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub size: Option<u64>,
    /// Local source path (source = file).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    /// Web page for manual downloads.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub page_url: Option<String>,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub manual: bool,
    /// Keys of required dependencies.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub deps: Vec<String>,
    /// Keys of projects declared incompatible.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub incompatible: Vec<String>,
    /// Fingerprints of the top-level specs that requested this entry directly.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub requested_by: Vec<String>,
}

impl LockEntry {
    pub fn matches_ident(&self, ident: &str) -> bool {
        let ident = ident.trim();
        let (src, id) = match ident.split_once(':') {
            Some((s, i)) if Source::parse(s).is_some() => (Source::parse(s), i),
            _ => (None, ident),
        };
        if let Some(s) = src {
            if s != self.source {
                return false;
            }
        }
        self.project_id.eq_ignore_ascii_case(id)
            || self.slug.as_deref().is_some_and(|s| s.eq_ignore_ascii_case(id))
            || self.filename.eq_ignore_ascii_case(id)
            || self.path.as_deref().is_some_and(|p| p.eq_ignore_ascii_case(id))
            || self.key.eq_ignore_ascii_case(ident)
    }
}

impl LockFile {
    pub fn load(pack_dir: &Path) -> Result<Option<LockFile>> {
        let p = pack_dir.join(LOCK_FILE);
        if !p.exists() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(&p).ctx(&p)?;
        Ok(Some(toml::from_str(&text)?))
    }

    pub fn save(&self, pack_dir: &Path) -> Result<()> {
        let mut text = String::from("# Generated by mcpack. Do not edit by hand; run `resolve` instead.\n");
        text.push_str(&toml::to_string_pretty(self)?);
        util::write_atomic(&pack_dir.join(LOCK_FILE), text.as_bytes())
    }

    pub fn get(&self, key: &str) -> Option<&LockEntry> {
        self.entries.iter().find(|e| e.key == key)
    }

    pub fn by_key(&self) -> HashMap<&str, &LockEntry> {
        self.entries.iter().map(|e| (e.key.as_str(), e)).collect()
    }

    /// Entries needed for the given top-level spec fingerprints (transitive closure over deps).
    pub fn closure(&self, top_fps: &[String]) -> Vec<&LockEntry> {
        let map = self.by_key();
        let mut keys: BTreeSet<&str> = BTreeSet::new();
        let mut stack: Vec<&str> = self
            .entries
            .iter()
            .filter(|e| e.requested_by.iter().any(|f| top_fps.contains(f)))
            .map(|e| e.key.as_str())
            .collect();
        while let Some(k) = stack.pop() {
            if !keys.insert(k) {
                continue;
            }
            if let Some(e) = map.get(k) {
                for d in &e.deps {
                    stack.push(d.as_str());
                }
            }
        }
        self.entries.iter().filter(|e| keys.contains(e.key.as_str())).collect()
    }
}
